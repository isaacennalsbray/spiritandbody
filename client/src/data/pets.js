// ── Species builder ────────────────────────────────────────────────────────────
// mk(id, name, type, rarity, hp, atk, def, spd, passive [, evolvesTo, evolvesAtLevel])
function mk(id, name, type, rarity, hp, atk, def, spd, passive, evo, evoLv) {
  return {
    id, name, type, rarity,
    baseHp: hp, baseAtk: atk, baseDef: def, baseSpd: spd,
    moves: [`${type}_1`, `${type}_2`, `${type}_3`, `${type}_4`],
    passive,
    isEvolution: false,
    ...(evo ? { evolvesTo: evo, evolvesAtLevel: evoLv } : {}),
  };
}
function mke(id, name, type, rarity, hp, atk, def, spd, passive) {
  return { ...mk(id, name, type, rarity, hp, atk, def, spd, passive), isEvolution: true };
}

