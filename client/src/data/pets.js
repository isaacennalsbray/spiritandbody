// ── Combat stat builder ───────────────────────────────────────────────────────
export function buildPetCombatant(id, speciesId, level, side) {
  const s = PET_SPECIES[speciesId];
  if (!s) throw new Error(`Unknown pet species: ${speciesId}`);
  const lv = Math.max(1, level);
  return {
    id,
    name:      s.name,
    speciesId,
    side,
    isPet:     true,
    type:      s.type,
    rarity:    s.rarity,
    level:     lv,
    passive:   s.passive || null,
    hp:        s.baseHp  + lv * 3,
    maxHp:     s.baseHp  + lv * 3,
    attack:    s.baseAtk + Math.floor(lv * 0.8),
    defense:   s.baseDef + Math.floor(lv * 0.8),
    speed:     s.baseSpd + Math.floor(lv * 0.6),
    moveIds:   [...s.moves],
    capturable: true,
    isBoss:    false,
    alive:     true,
    captured:  false,
    status:    null,
    statusTurns: 0,
  };
}
